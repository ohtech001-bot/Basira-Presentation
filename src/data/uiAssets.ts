import { getUiAssetUrl } from '../utils/offlineAssets';

export interface UiAsset {
  id: string;
  title: string;
  description: string;
  /** Original user-supplied filename, retained unmodified under ui/. */
  sourceFile: string;
  /** Optimized display filename under public/assets/ui/. */
  servedFile: string;
  src: string;
  width: number;
  height: number;
  sourceWidth: number;
  sourceHeight: number;
}

const asset = (
  id: string,
  title: string,
  description: string,
  sourceFile: string,
  servedFile: string,
  width: number,
  height: number,
  sourceWidth = width,
  sourceHeight = height,
): UiAsset => ({
  id,
  title,
  description,
  sourceFile,
  servedFile,
  width,
  height,
  sourceWidth,
  sourceHeight,
  src: getUiAssetUrl(servedFile),
});

